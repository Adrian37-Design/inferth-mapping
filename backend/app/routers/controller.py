def parse_xcela_timestamp(date_str: Optional[str]) -> datetime:
    """Parse Xcela tracker dates like '13/10/2026 17:45:00 GMT' or fallback to UTC now."""
    if not date_str:
        return datetime.utcnow()
    
    clean = date_str.replace(" GMT", "").replace(" UTC", "").strip()
    formats = [
        "%d/%m/%Y %H:%M:%S",
        "%Y-%m-%d %H:%M:%S",
        "%Y-%m-%dT%H:%M:%S",
        "%d-%m-%Y %H:%M:%S"
    ]
    for fmt in formats:
        try:
            return datetime.strptime(clean, fmt)
        except ValueError:
            continue
    
    return datetime.utcnow()


@router.post("/upsert")
async def upsert_tracking_data(
    request: Request,
    db: AsyncSession = Depends(get_db)
):
    """
    Ingest live tracking and historical replay data from Xcela ESP32 trackers.
    Accepts JSON body generated by Malkon Xcela firmware R19.
    """
    try:
        body = await request.json()
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"Invalid JSON payload: {e}")

    imei = body.get("imei")
    data_points = body.get("data", [])
    
    if not imei:
        # Fallback: check Cookie or query or device header if IMEI not directly in body
        cookies = request.cookies
        token = cookies.get("token")
        # If still missing and data points exist, reject
        if not token:
            return {"success": False, "error": "Missing IMEI or device token"}
        imei = f"XCELA-{abs(hash(token)) % 10000000000:010d}"

    # Find or auto-create device for Tenant 1
    stmt = select(Device).where(Device.imei == str(imei).strip())
    res = await db.execute(stmt)
    device = res.scalars().first()

    if not device:
        device = Device(
            imei=str(imei).strip(),
            name=f"Xcela {body.get('modem_name', 'Tracker')} ({str(imei)[-6:]})",
            tenant_id=1,
            device_metadata={}
        )
        db.add(device)
        await db.commit()
        await db.refresh(device)

    # Update device metadata with latest hardware telemetry
    meta = dict(device.device_metadata or {})
    if "is_engine_locked" in body:
        meta["is_engine_locked"] = body["is_engine_locked"]
        meta["is_shutdown"] = bool(body["is_engine_locked"])
    if "signal_quality" in body:
        meta["signal_quality"] = body["signal_quality"]
    if "operator_name" in body:
        meta["operator_name"] = body["operator_name"]
    if "modem_name" in body:
        meta["modem_name"] = body["modem_name"]
    if "ip_address" in body:
        meta["ip_address"] = body["ip_address"]
    
    meta["last_seen"] = datetime.utcnow().isoformat()
    device.device_metadata = meta

    inserted_count = 0
    now = datetime.utcnow()

    # Process each coordinate point
    for row in data_points:
        raw_lat = row.get("lat")
        raw_lon = row.get("lon")
        
        # 1. Coordinate sanitation
        clean_lat, clean_lon, valid_coords = validate_coordinates(raw_lat, raw_lon)
        if not valid_coords:
            continue

        # 2. Speed clamping
        clean_speed = validate_and_sanitize_speed(row.get("speed", 0.0))

        # 3. Timestamp validation
        dt_cand = parse_xcela_timestamp(row.get("time_to") or row.get("time_from"))
        timestamp = validate_timestamp(dt_cand, fallback_now=now)

        # Teleportation and deduplication checks
        prev_q = await db.execute(
            select(Position)
            .where(Position.device_id == device.id, Position.latitude.is_not(None), Position.longitude.is_not(None))
            .order_by(Position.timestamp.desc())
            .limit(1)
        )
        prev_pos = prev_q.scalars().first()

        if prev_pos and prev_pos.latitude and prev_pos.longitude:
            if is_teleportation_jump(
                prev_pos.latitude, prev_pos.longitude, prev_pos.timestamp,
                clean_lat, clean_lon, timestamp
            ):
                continue
            if is_duplicate_ping(
                prev_pos.latitude, prev_pos.longitude, prev_pos.speed or 0.0, prev_pos.timestamp,
                clean_lat, clean_lon, clean_speed, timestamp
            ):
                continue

        # Extract CAN/telemetry fields
        fuel = row.get("fuel_level")
        vbatt = row.get("vbatt")
        ign = row.get("ignition")
        altitude = row.get("altitude")
        course = row.get("course")

        pos = Position(
            device_id=device.id,
            latitude=clean_lat,
            longitude=clean_lon,
            altitude=float(altitude) if altitude is not None else None,
            speed=clean_speed,
            course=float(course) if course is not None else None,
            timestamp=timestamp,
            fuel_level=float(fuel) if fuel is not None else None,
            battery_voltage=float(vbatt) if vbatt is not None else None,
            ignition=bool(ign) if ign is not None else None,
            raw=row
        )
        db.add(pos)
        inserted_count += 1

        # Realtime WebSocket broadcasting
        publish_position(device.id, {
            "device_id": device.id,
            "imei": device.imei,
            "name": device.name,
            "latitude": clean_lat,
            "longitude": clean_lon,
            "speed": clean_speed,
            "altitude": altitude,
            "course": course,
            "fuel_level": fuel,
            "battery_voltage": vbatt,
            "ignition": ign,
            "timestamp": timestamp.isoformat()
        })

    await db.commit()
    return {"success": True, "count": inserted_count}


@router.get("/get-commands")
async def get_commands(
    request: Request,
    imei: Optional[str] = None,
    db: AsyncSession = Depends(get_db)
):
    """
    Tracker polls this endpoint periodically to receive remote engine lock/unlock commands.
    """
    commands_to_send = []

    # If imei passed in query or found in device lookup
    if imei:
        res = await db.execute(select(Device).where(Device.imei == imei.strip()))
        device = res.scalars().first()
        if device and device.device_metadata:
            meta = dict(device.device_metadata)
            pending = meta.get("pending_command")
            if pending:
                if pending in ["SHUTDOWN", "SLEEP", "LOCK"]:
                    commands_to_send.append({"code": "ENGINE_LOCK"})
                elif pending in ["RESTORE", "UNLOCK"]:
                    commands_to_send.append({"code": "ENGINE_UN_LOCK"})
                # Clear pending once delivered
                meta.pop("pending_command", None)
                device.device_metadata = meta
                await db.commit()

    return {
        "success": True,
        "data": {
            "controller_commands": commands_to_send
        }
    }


@router.post("/sos-alerts")
async def handle_sos_alerts(
    request: Request,
    db: AsyncSession = Depends(get_db)
):
    """Handle panic button and accident alerts from the Xcela tracker."""
    try:
        body = await request.json()
    except Exception:
        body = {}

    imei = body.get("imei", "UNKNOWN")
    alert_type = body.get("type", "SOS_PANIC")
    message = body.get("message", "Emergency button triggered on vehicle")

    # Look up device
    res = await db.execute(select(Device).where(Device.imei == str(imei).strip()))
    device = res.scalars().first()
    tenant_id = device.tenant_id if device else 1
    device_id = device.id if device else None

    alert = Alert(
        tenant_id=tenant_id,
        device_id=device_id,
        type=alert_type,
        message=f"[{device.name if device else imei}] {message}",
        timestamp=datetime.utcnow()
    )
    db.add(alert)
    await db.commit()

    return {"success": True}


