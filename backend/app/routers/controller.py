def extract_plate_from_jwt(token: Optional[str]) -> Optional[str]:
    """Extract configured vehicle number plate or ID from Xcela tracker JWT token."""
    if not token:
        return None
    try:
        parts = token.strip().split(".")
        if len(parts) >= 2:
            payload = parts[1]
            rem = len(payload) % 4
            if rem > 0:
                payload += "=" * (4 - rem)
            decoded_bytes = base64.urlsafe_b64decode(payload)
            data = json.loads(decoded_bytes.decode("utf-8"))
            return data.get("number_plate") or data.get("vehicle_id") or data.get("plate")
    except Exception:
        pass
    return None


def parse_xcela_timestamp(date_str: Optional[str]) -> datetime:
    """Parse Xcela tracker dates like '13/10/2026 17:45:00 GMT' or fallback to UTC now."""
    if not date_str:
        return datetime.utcnow()
    
    clean = date_str.replace(" GMT", "").replace(" UTC", "").strip()
    formats = [
        "%m/%d/%Y %H:%M:%S",
        "%d/%m/%Y %H:%M:%S",
        "%Y-%m-%d %H:%M:%S",
        "%Y-%m-%dT%H:%M:%S",
        "%d-%m-%Y %H:%M:%S"
    ]
    for fmt in formats:
        try:
            return datetime.strptime(clean, fmt)
        except ValueError:
            continue
    
    return datetime.utcnow()


@router.post("/upsert")
async def upsert_tracking_data(
    request: Request,
    db: AsyncSession = Depends(get_db)
):
    """
    Ingest live tracking and historical replay data from Xcela ESP32 trackers.
    Accepts JSON body generated by Malkon Xcela firmware R19.
    """
    try:
        body = await request.json()
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"Invalid JSON payload: {e}")

    data_points = body.get("data", [])
    cookies = request.cookies
    token = cookies.get("token") or request.headers.get("Authorization", "").replace("Bearer ", "")
    jwt_plate = extract_plate_from_jwt(token)

    # Clean identity: IMEI from body, or number plate from JWT, or fallback to XYZ4321
    raw_ident = body.get("imei") or jwt_plate or "XYZ4321"
    ident = str(raw_ident).strip()

    # Look up authoritative device:
    # 1. Exact match on IMEI
    device = None
    res = await db.execute(select(Device).where(Device.imei == ident))
    device = res.scalars().first()

    # 2. Match short suffix if plate length is 7 (e.g. YZ4321)
    if not device and len(ident) >= 6:
        res = await db.execute(select(Device).where(Device.imei == ident[-6:]))
        device = res.scalars().first()

    # 3. Match device name containing YZ4321 or XYZ4321
    if not device and len(ident) >= 6:
        res = await db.execute(select(Device).where(Device.name.ilike(f"%{ident[-6:]}%")))
        device = res.scalars().first()

    # 4. Match device named "Xcela Tracker"
    if not device:
        res = await db.execute(select(Device).where(Device.name.ilike("%Xcela Tracker%")))
        device = res.scalars().first()

    # 5. If STILL not found, create the ONE legitimate device (never use hash!)
    if not device:
        suffix = ident[-6:] if len(ident) >= 6 else ident
        device = Device(
            imei=ident,
            name=f"Xcela Tracker ({suffix})",
            tenant_id=1,
            device_metadata={}
        )
        db.add(device)
        await db.commit()
        await db.refresh(device)

    # Purge phantom devices created by historical hash collisions
    try:
        phantom_q = await db.execute(
            select(Device).where(
                ((Device.name.ilike("Xcela AT+CGMI%")) | (Device.imei.like("XCELA-%"))),
                Device.id != device.id
            )
        )
        phantoms = phantom_q.scalars().all()
        if phantoms:
            for p in phantoms:
                await db.execute(
                    update(Position).where(Position.device_id == p.id).values(device_id=device.id)
                )
                await db.execute(
                    update(Alert).where(Alert.device_id == p.id).values(device_id=device.id)
                )
                await db.delete(p)
            await db.commit()
    except Exception as e:
        print(f"[CLEANUP] Error purging phantom devices: {e}")

    # Update device metadata with latest hardware telemetry
    meta = dict(device.device_metadata or {})
    if "is_engine_locked" in body:
        meta["is_engine_locked"] = body["is_engine_locked"]
        meta["is_shutdown"] = bool(body["is_engine_locked"])
    if "signal_quality" in body:
        meta["signal_quality"] = body["signal_quality"]
    if "operator_name" in body:
        meta["operator_name"] = body["operator_name"]
    if "modem_name" in body:
        meta["modem_name"] = body["modem_name"]
    if "ip_address" in body:
        meta["ip_address"] = body["ip_address"]
    
    meta["last_seen"] = datetime.utcnow().isoformat() + "Z"
    device.device_metadata = meta

    inserted_count = 0
    now = datetime.utcnow()

    # Process each coordinate point
    for row in data_points:
        raw_lat = row.get("lat")
        raw_lon = row.get("lon")
        
        # 1. Coordinate sanitation
        clean_lat, clean_lon, valid_coords = validate_coordinates(raw_lat, raw_lon)
        if not valid_coords:
            continue

        # 2. Speed clamping
        clean_speed = validate_and_sanitize_speed(row.get("speed", 0.0))

        # 3. Timestamp validation
        dt_cand = parse_xcela_timestamp(row.get("time_to") or row.get("time_from"))
        timestamp = validate_timestamp(dt_cand, fallback_now=now)

        # Teleportation and deduplication checks
        prev_q = await db.execute(
            select(Position)
            .where(Position.device_id == device.id, Position.latitude.is_not(None), Position.longitude.is_not(None))
            .order_by(Position.timestamp.desc())
            .limit(1)
        )
        prev_pos = prev_q.scalars().first()

        if prev_pos and prev_pos.latitude and prev_pos.longitude:
            if is_teleportation_jump(
                prev_pos.latitude, prev_pos.longitude, prev_pos.timestamp,
                clean_lat, clean_lon, timestamp
            ):
                continue
            if is_duplicate_ping(
                prev_pos.latitude, prev_pos.longitude, prev_pos.speed or 0.0, prev_pos.timestamp,
                clean_lat, clean_lon, clean_speed, timestamp
            ):
                continue

        # Extract CAN/telemetry fields
        fuel = row.get("fuel_level")
        vbatt = row.get("vbatt")
        ign = row.get("ignition")
        altitude = row.get("altitude")
        course = row.get("course")

        pos = Position(
            device_id=device.id,
            latitude=clean_lat,
            longitude=clean_lon,
            altitude=float(altitude) if altitude is not None else None,
            speed=clean_speed,
            course=float(course) if course is not None else None,
            timestamp=timestamp,
            fuel_level=float(fuel) if fuel is not None else None,
            battery_voltage=float(vbatt) if vbatt is not None else None,
            ignition=bool(ign) if ign is not None else None,
            raw=row
        )
        db.add(pos)
        inserted_count += 1

        # Realtime WebSocket broadcasting — only for fresh positions.
        # Backfilled offline rows keep their original (older) timestamps;
        # broadcasting them makes the live marker jump backwards to stale
        # coordinates. They are still stored above for history/route playback.
        prev_ts = _to_naive_utc(prev_pos.timestamp) if (prev_pos and prev_pos.timestamp) else None
        if prev_ts is None or timestamp >= prev_ts:
            try:
                await publish_position({
                    "device_id": device.id,
                    "imei": device.imei,
                    "name": device.name,
                    "latitude": clean_lat,
                    "longitude": clean_lon,
                    "speed": clean_speed,
                    "altitude": altitude,
                    "course": course,
                    "fuel_level": fuel,
                    "battery_voltage": vbatt,
                    "ignition": ign,
                    "timestamp": timestamp.isoformat() + "Z"
                })
            except Exception:
                pass

    await db.commit()
    return {"success": True, "count": inserted_count}


@router.get("/cleanup-phantoms")
async def cleanup_phantoms_endpoint(
    db: AsyncSession = Depends(get_db)
):
    """Purge phantom devices created during earlier testing."""
    # Find the real target device
    res = await db.execute(select(Device).where(Device.name.ilike("%YZ4321%")))
    real_device = res.scalars().first()
    if not real_device:
        res = await db.execute(select(Device).where(Device.imei.in_(["XYZ4321", "YZ4321"])))
        real_device = res.scalars().first()
    if not real_device:
        res = await db.execute(select(Device).where(Device.name.ilike("%Xcela Tracker%")))
        real_device = res.scalars().first()

    purged_count = 0
    if real_device:
        phantom_q = await db.execute(
            select(Device).where(
                ((Device.name.ilike("Xcela AT+CGMI%")) | (Device.imei.like("XCELA-%"))),
                Device.id != real_device.id
            )
        )
        phantoms = phantom_q.scalars().all()
        purged_count = len(phantoms)
        for p in phantoms:
            await db.execute(
                update(Position).where(Position.device_id == p.id).values(device_id=real_device.id)
            )
            await db.execute(
                update(Alert).where(Alert.device_id == p.id).values(device_id=real_device.id)
            )
            await db.delete(p)
        await db.commit()

    return {"success": True, "purged": purged_count, "real_device": real_device.name if real_device else None}


@router.get("/get-commands")
async def get_commands(
    request: Request,
    imei: Optional[str] = None,
    db: AsyncSession = Depends(get_db)
):
    """
    Tracker polls this endpoint periodically to receive remote engine lock/unlock commands.
    """
    commands_to_send = []

    # If imei not passed in query, resolve from JWT cookie or fallback
    if not imei:
        cookies = request.cookies
        token = cookies.get("token") or request.headers.get("Authorization", "").replace("Bearer ", "")
        imei = extract_plate_from_jwt(token) or "XYZ4321"

    ident = str(imei).strip()
    device = None
    res = await db.execute(select(Device).where(Device.imei == ident))
    device = res.scalars().first()
    if not device and len(ident) >= 6:
        res = await db.execute(select(Device).where(Device.imei == ident[-6:]))
        device = res.scalars().first()
    if not device and len(ident) >= 6:
        res = await db.execute(select(Device).where(Device.name.ilike(f"%{ident[-6:]}%")))
        device = res.scalars().first()
    if not device:
        res = await db.execute(select(Device).where(Device.name.ilike("%Xcela Tracker%")))
        device = res.scalars().first()

    if device and device.device_metadata:
        meta = dict(device.device_metadata)
        pending = meta.get("pending_command")
        if pending:
            if pending in ["SHUTDOWN", "SLEEP", "LOCK"]:
                commands_to_send.append({"code": "ENGINE_LOCK"})
            elif pending in ["RESTORE", "UNLOCK"]:
                commands_to_send.append({"code": "ENGINE_UN_LOCK"})
            # Clear pending once delivered
            meta.pop("pending_command", None)
            device.device_metadata = meta
            await db.commit()

    return {
        "success": True,
        "data": {
            "controller_commands": commands_to_send
        }
    }


@router.post("/sos-alerts")
async def handle_sos_alerts(
    request: Request,
    db: AsyncSession = Depends(get_db)
):
    """Handle panic button and accident alerts from the Xcela tracker."""
    try:
        body = await request.json()
    except Exception:
        body = {}

    imei = body.get("imei", "UNKNOWN")
    alert_type = body.get("type", "SOS_PANIC")
    message = body.get("message", "Emergency button triggered on vehicle")

    # Look up device
    res = await db.execute(select(Device).where(Device.imei == str(imei).strip()))
    device = res.scalars().first()
    tenant_id = device.tenant_id if device else 1
    device_id = device.id if device else None

    alert = Alert(
        tenant_id=tenant_id,
        device_id=device_id,
        type=alert_type,
        message=f"[{device.name if device else imei}] {message}",
        timestamp=datetime.utcnow()
    )
    db.add(alert)
    await db.commit()

    return {"success": True}


